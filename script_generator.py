def generate_script(topic):
    """
    Generates a script for a YouTube Short based on a topic.
    """
    script = f"""
**Host:** Welcome back to our channel! Today, we're diving into a fascinating topic: {topic}.

**Host:** Did you know that {topic} is more complex than it seems? Let's break it down.

**Host:** First, we have the core concept. This is the foundation of everything we know about {topic}.

**Host:** Next, there are the major developments. These events shaped {topic} into what it is today.

**Host:** And finally, the future. Where is {topic} headed? The possibilities are endless!

**Host:** Thanks for watching! Don't forget to like and subscribe for more content like this.
"""
    return script
